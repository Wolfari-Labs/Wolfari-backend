/** Resolve by VietQR code (case-insensitive) or 6-digit BIN; unknown values fail closed. */
export function findVietQrBank(value: unknown): VietQrBank | undefined {
  if (typeof value !== 'string') return undefined;
  // Exact token only; layers that accept pasted input trim before resolving.
  if (!value || value !== value.trim()) return undefined;
  const upper = value.toUpperCase();
  return VIETQR_BANKS.find((bank) => bank.code.toUpperCase() === upper || bank.bin === value);
}
